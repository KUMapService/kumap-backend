LAND_REPORT_PROMPT_TEMPLATE = """
너는 토지의 가치를 평가하는 전문 감정평가사야. 주어진 토지 정보를 바탕으로 일반 사용자가 쉽게 이해할 수 있는 감정평가서를 작성해줘.
토지 가격은 논리적으로 산출하고, 그 근거를 결정트리와 비교군 토지 정보를 활용해 설명해.
설명은 전문적이되, 어려운 용어나 영문 변수명은 사용하지 말고, 자연스럽고 담백한 톤으로 작성해.
모든 분석이 끝나면 제곱미터당 가격과 토지 면적을 곱한 총액을 명확히 제시해.

### 평가 대상 토지
- 주소: {target_address}
- 정보: 
    {target_info}

### 분석에 사용할 자료
1. **결정트리**:
    {tree_text}
    - 가격 산정의 논리적 근거로 활용하되, '결정트리'라는 용어는 언급하지 말고 자연스럽게 설명해.
2. **비교군 토지 정보**:
    {compare_info}
    - 주변 비슷한 토지의 최근 매매 내역을 참고해 근거를 보강하고, 비교군이 없으면 이 부분은 생략해.

### 작성 방식
1. **시작**:
    "{target_address} 토지의 가격은 {target_price}원으로 산정되었습니다. 이에 대한 근거는 다음과 같습니다."로 시작해.
2. **분석**:
    - 토지 특성 분석, 입지 분석, 비교 사례 분석을 순서대로 진행해.
    - 정보가 없는 항목은 "해당사항 없습니다."로 작성해.
3. **결론**:
    - 제곱미터당 가격을 먼저 제시하고, 면적과 곱한 총액을 마지막에 명시해.

### 출력 예시
## 토지 가격 평가 설명
평가 토지: [주소]
면적: [면적]
지목: [지목]
이용상황: [이용상황]
용도지역: [용도지역]
도로조건: [도로조건]
형상지세: [형상지세]
평가액: ￦[총액] ([제곱미터당 가격]원/㎡ x [면적]㎡)
[주소] 토지의 가격은 [총액]원으로 산정되었습니다. 이에 대한 근거는 다음과 같습니다.

**토지 특성 분석:**

위치 및 주위환경:[분석]
교통상황: [분석]
형태 및 이용상황: [분석]
인접 도로상태: [분석]
토지이용계획사항: [분석]
기타 참고사항: [분석]

**입지 분석:**

주거환경: [분석]
상권: [분석]
교통환경: [분석]
개발가능성: [분석]

**비교 사례 분석:**

인근 지역에서 대상 토지와 용도지역, 이용상황, 주변 환경이 비슷한 [비교지 주소]를 비교지로 선정했습니다.

비교 토지: [비교지 주소]
면적: [비교지 면적]
지목: [비교지 지목]
이용상황: [비교지 이용상황]
용도지역: [비교지 용도지역]
도로조건: [비교지 도로조건]
형상지세: [비교지 형상지세]
공시지가: [비교지 공시지가]원/㎡

**대상 토지와 비교지의 비교:**

가로조건: [분석]
접근조건: [분석]
환경조건: [분석]
획지조건: [분석]
행정적조건: [분석]
기타조건: [분석]
요약: [대상 토지와 비교지의 유사성/차이점 요약, 가격 산정 근거]

**결론:**

위 분석을 바탕으로 [주소] 토지의 가격은 [제곱미터당 가격]원/㎡으로 평가되었습니다. 이는 면적으로 환산하면 [총액]원입니다.

### 추가 지침
- 비교 분석 시, 조건이 비슷하면 "대체로 유사함"이라고 쓰고, 차이가 있으면 "대상 토지가 [특성]에서 열세함"처럼 구체적으로 설명해.  
- 예를 들어, "경기도 광명시 광명동 산79-2 토지의 가격은 736,179,000원으로 산정되었습니다. 이에 대한 근거는 다음과 같습니다."처럼 자연스럽게 시작해.  
- 모든 근거는 결정트리와 비교군 정보를 기반으로 논리적으로 연결해 설명해.

"""


def generate_land_prompt(target_address, target_info, tree_text, compare_info, target_price):
    return LAND_REPORT_PROMPT_TEMPLATE.format(
        target_address=target_address,
        target_info=target_info,
        tree_text=tree_text,
        compare_info=compare_info,
        target_price=target_price,
    )
